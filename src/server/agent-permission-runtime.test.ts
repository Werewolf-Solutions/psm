import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import test from "node:test";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { openDatabase } from "./db.ts";
import { AgentPermissionStore } from "./agent-permissions.ts";
import { createManagedRepositoryServer } from "./agent-permission-runtime.ts";

test("SDK MCP transport stages and commits without approval and cannot self-grant", async (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "psm-permission-sdk-"));
  const database = openDatabase(":memory:");
  const store = new AgentPermissionStore(() => database);
  const project = { id: "prj_test", name: "test", path: root };
  const git = (...args: string[]) => execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] });
  git("init", "-q"); git("config", "user.name", "PSM Test"); git("config", "user.email", "psm-test@example.invalid");
  fs.writeFileSync(path.join(root, "app.txt"), "before\n"); git("add", "."); git("commit", "-qm", "initial");
  for (const permission of ["repo.read", "repo.edit", "git.commit"]) store.change(project, permission, true, store.snapshot(project).revision, "operator");
  const abort = new AbortController();
  const server = createManagedRepositoryServer({ store, snapshots: [store.snapshot(project)], protectedRoots: [] }, abort);
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  const client = new Client({ name: "psm-test", version: "1" });
  t.after(async () => { await client.close(); await server.instance.close(); database.close(); fs.rmSync(root, { recursive: true, force: true }); });
  await server.instance.connect(serverTransport);
  await client.connect(clientTransport);
  const tools = await client.listTools();
  assert.ok(tools.tools.some((tool) => tool.name === "git_commit"));
  assert.ok(!tools.tools.some((tool) => /bash|shell|grant/.test(tool.name)));
  for (const name of ["delete", "git_switch", "git_merge", "git_fetch", "git_push", "install_packages"]) {
    assert.ok(tools.tools.some((tool) => tool.name === name), `${name} should be brokered`);
  }
  const call = (name: string, args: Record<string, unknown>) => client.callTool({ name, arguments: { project: project.id, ...args } });
  assert.equal((await call("run_tests", { script: "test" })).isError, true);
  assert.equal((await call("install_packages", {})).isError, true);
  assert.equal((await call("write", { file: ".claude/settings.local.json", content: "grant everything" })).isError, true);
  assert.equal((await call("write", { file: "app.txt", content: "fixed\n" })).isError, undefined);
  assert.equal((await call("git_stage", { files: ["app.txt"] })).isError, undefined);
  assert.equal((await call("git_commit", { message: "repair through MCP" })).isError, undefined);
  assert.equal(git("show", "HEAD:app.txt"), "fixed\n");
  assert.equal((await call("read", { project: "prj_other", file: "app.txt" })).isError, true);
  // Agents often pass the project's name; it resolves when unambiguous.
  assert.match(JSON.stringify((await call("read", { project: project.name, file: "app.txt" })).content), /fixed/);
  assert.match(JSON.stringify((await call("read", { project: "other", file: "app.txt" })).content), /Projects in scope: test \(prj_test\)/);
  fs.writeFileSync(path.join(root, "package.json"), JSON.stringify({ scripts: { build: "tsc && vite build" }, dependencies: { react: "19" } }));
  git("add", "package.json"); git("commit", "-qm", "website manifest");
  await call("write", { file: "app.txt", content: "unverified website edit\n" });
  await call("git_stage", { files: ["app.txt"] });
  const blocked = await call("git_commit", { message: "must verify first" });
  assert.equal(blocked.isError, true);
  assert.match(JSON.stringify(blocked.content), /Commit blocked.*build.*browser preview/);
  assert.equal(git("show", "HEAD:app.txt"), "fixed\n");
  assert.match(JSON.stringify((await call("verification_status", {})).content), /\\"verified\\":false/);
    store.change(project, "repo.edit", false, store.snapshot(project).revision, "operator");
  const revoked = await call("write", { file: "app.txt", content: "forbidden\n" });
  assert.equal(revoked.isError, true);
  assert.match(JSON.stringify(revoked.content), /permissions changed/);
  assert.equal(fs.readFileSync(path.join(root, "app.txt"), "utf8"), "unverified website edit\n");
});
